// Dev-only: prints the section inventory and URL map used in handover/MIGRATION-NOTES.md.
// Usage: node build/inventory.mjs > handover/section-inventory.md

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PAGES = path.join(ROOT, 'src', 'pages');
const PARTIALS = path.join(ROOT, 'src', 'partials');
const site = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'site.json'), 'utf8'));

function walk(dir, base = '') {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full, `${base}${entry.name}/`);
    return entry.name.endsWith('.html') ? [{ file: full, route: entry.name === 'index.html' ? base : entry.name }] : [];
  });
}

function sectionsIn(html) {
  const found = [];
  for (const m of html.matchAll(/<section\b[^>]*data-section="([^"]+)"|\{\{\s*include:([a-z-]+)\s*\}\}/g)) {
    if (m[1]) {
      found.push(m[1]);
    } else {
      const partial = fs.readFileSync(path.join(PARTIALS, `${m[2]}.html`), 'utf8');
      for (const inner of partial.matchAll(/<section\b[^>]*data-section="([^"]+)"/g)) found.push(`${inner[1]} (${m[2]} partial)`);
    }
  }
  return found;
}

const pages = walk(PAGES).sort((a, b) => a.route.localeCompare(b.route));
const lines = [];
lines.push('| Static path | WordPress permalink | Page title | Containers in order |');
lines.push('|---|---|---|---|');
for (const page of pages) {
  const raw = fs.readFileSync(page.file, 'utf8');
  const meta = JSON.parse(raw.match(/^<!--page\s*([\s\S]*?)-->/)[1]);
  const staticPath = page.route === '404.html' ? '/404.html' : `/${page.route}`;
  const permalink = page.route === '404.html' ? 'Theme 404 template' : page.route === '' ? '/ (front page)' : `/${page.route}`;
  const title = meta.title.replace(/\{\{\s*([^}]+?)\s*\}\}/g, '[$1]').replace(/\|/g, '\\|').trim();
  lines.push(`| \`${staticPath}\` | \`${permalink}\` | ${title} | ${sectionsIn(raw).join(' → ')} |`);
}

console.log(`<!-- Generated by build/inventory.mjs for ${site.brand.name}. Do not edit by hand. -->\n`);
console.log(lines.join('\n'));
